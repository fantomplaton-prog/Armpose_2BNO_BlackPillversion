# -*- coding: utf-8 -*-
"""
posetracker - определение положения руки относительно тела по двум
IMU-датчикам (BNO08x на STM32, подключение по BLE), без магнитометра.

ЧТО ТАКОЕ __init__.py И ЗАЧЕМ ОН ЗДЕСЬ:
Файл с именно этим именем в папке - то, что превращает обычную папку с
.py-файлами в ПАКЕТ (`import posetracker` работает только потому, что
внутри папки posetracker/ есть __init__.py). Это ближайший Python-аналог
"публичного заголовочного файла" из C: остальные файлы пакета
(ble_link.py, calibration.py, pose.py, quat.py, tracker.py) - это
"внутренние .c-файлы" библиотеки, а __init__.py явно решает, что из них
видно СНАРУЖИ пакета.

Без реэкспорта здесь потребителю пришлось бы писать длинно и знать
внутреннее устройство пакета:
    from posetracker.tracker import PoseTracker
    from posetracker.pose import PoseResult
А благодаря строкам ниже - достаточно короткого и не зависящего от
внутренней раскладки файлов:
    from posetracker import PoseTracker, PoseResult
Если завтра захочется переименовать tracker.py в engine.py или
переставить классы по другим файлам - ни один потребитель пакета этого
не заметит, пока не поменялся набор имён в __init__.py. Это и есть
инкапсуляция на уровне пакета: внутренняя раскладка файлов - деталь
реализации, а не часть контракта с потребителем.

ЧТО ТАКОЕ "from .tracker import ..." (точка перед именем модуля):
Точка - это ОТНОСИТЕЛЬНЫЙ импорт: "модуль tracker.py из ЭТОГО ЖЕ пакета",
а не "какой-то модуль tracker, который найдётся в sys.path". Без точки
Python искал бы модуль с именем "tracker" по всем известным путям (и мог
бы случайно найти чужой одноимённый модуль откуда-то ещё) - относительный
импорт однозначно указывает "бери отсюда же, из соседнего файла внутри
пакета".

ПОЧЕМУ __all__ (список ниже):
__all__ - это то, что подхватит `from posetracker import *` (если кто-то
так сделает), и заодно явная декларация "вот полный список того, что
пакет считает своим публичным API" - как список экспортируемых символов
в модульном определении на других языках. Не обязательно строго
техническое требование (можно было бы обойтись и без него), но хорошая
практика для любого пакета, который задуман для импорта извне.
"""

